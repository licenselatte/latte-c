#include <string.h>

/*
 * The y-coordinates of every point of order 1, 2, 4 or 8, including the
 * non-canonical encodings of 0 and 1. The sign bit is ignored.
 */
static const unsigned char small_order[7][32] = {
    /* 0 (order 4) */
    {0},
    /* 1 (order 1) */
    {1},
    /* order 8 */
    {0x26, 0xe8, 0x95, 0x8f, 0xc2, 0xb2, 0x27, 0xb0, 0x45, 0xc3, 0xf4, 0x89, 0xf2, 0xef, 0x98, 0xf0,
     0xd5, 0xdf, 0xac, 0x05, 0xd3, 0xc6, 0x33, 0x39, 0xb1, 0x38, 0x02, 0x88, 0x6d, 0x53, 0xfc, 0x05},
    /* order 8 */
    {0xc7, 0x17, 0x6a, 0x70, 0x3d, 0x4d, 0xd8, 0x4f, 0xba, 0x3c, 0x0b, 0x76, 0x0d, 0x10, 0x67, 0x0f,
     0x2a, 0x20, 0x53, 0xfa, 0x2c, 0x39, 0xcc, 0xc6, 0x4e, 0xc7, 0xfd, 0x77, 0x92, 0xac, 0x03, 0x7a},
    /* p - 1 (order 2) */
    {0xec, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
     0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x7f},
    /* p, a non-canonical 0 */
    {0xed, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
     0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x7f},
    /* p + 1, a non-canonical 1 */
    {0xee, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
     0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x7f},
};

int ll_ed25519_point_ok(const unsigned char p[32])
{
    for (size_t i = 0; i < sizeof(small_order) / sizeof(small_order[0]); i++)
        if (memcmp(p, small_order[i], 31) == 0 && (p[31] & 0x7f) == small_order[i][31])
            return 0;

    /* y >= p = 2^255 - 19: bytes 1..30 all 0xff, top byte 0x7f, low byte >= 0xed. */
    if ((p[31] & 0x7f) != 0x7f || p[0] < 0xed) return 1;
    for (int i = 1; i < 31; i++)
        if (p[i] != 0xff) return 1;
    return 0;
}

/*
 * Monocypher rejects S >= L and points off the curve but accepts small-order
 * and non-canonical points (a small-order key verifies forged signatures for
 * any message), so those are refused here first.
 */
int ll_ed25519_verify(const unsigned char sig[64],
                      const unsigned char *msg, size_t msg_len,
                      const unsigned char pk[32])
{
    if (!ll_ed25519_point_ok(sig) || !ll_ed25519_point_ok(pk)) return -1;
    return crypto_ed25519_check(sig, pk, msg, msg_len) == 0 ? 0 : -1;
}
